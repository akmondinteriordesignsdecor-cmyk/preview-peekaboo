-- Run with psql and ON_ERROR_STOP; all fixtures roll back.
BEGIN;
DO $$
DECLARE seller uuid; buyer uuid; starter uuid; pro uuid; team uuid; ref text; quote json; payment public.payments%ROWTYPE; ownership uuid; listing uuid; sess json; sess_id uuid; before_count int; outcome text;
BEGIN
SELECT id INTO seller FROM public.profiles ORDER BY created_at LIMIT 1;
SELECT id INTO buyer FROM public.profiles WHERE id<>seller ORDER BY created_at LIMIT 1;
IF seller IS NULL OR buyer IS NULL THEN RAISE EXCEPTION 'Two existing accounts are required'; END IF;
SELECT id INTO starter FROM public.plans WHERE name='Starter NFT';
SELECT id INTO pro FROM public.plans WHERE name='Pro NFT';
SELECT id INTO team FROM public.plans WHERE name='Team NFT';
IF starter IS NULL OR pro IS NULL OR team IS NULL THEN RAISE EXCEPTION 'Named NFT plans missing'; END IF;
-- Isolate fixtures without deleting financial history.
UPDATE public.nft_ownerships SET plan_purchase_id=NULL, nft_id=(SELECT id FROM public.nfts WHERE mining_plan_id IS NULL LIMIT 1) WHERE user_id IN(seller,buyer) AND plan_purchase_id IS NOT NULL;
UPDATE public.mining_sessions SET status='cancelled' WHERE user_id IN(seller,buyer) AND status IN('active','completed');
UPDATE public.payments SET status='failed' WHERE user_id IN(seller,buyer) AND status='pending';
SELECT count(*) INTO before_count FROM public.nft_ownerships WHERE user_id=seller AND plan_purchase_id IS NOT NULL;
quote:=public.prepare_checkout_for_user(seller,'plan',starter,NULL,1600);
SELECT * INTO payment FROM public.payments WHERE reference=quote->>'reference';
IF payment.amount_usd<>2 THEN RAISE EXCEPTION 'Starter must cost $2'; END IF;
outcome:=public.fulfill_payment(payment.reference,payment.amount_ngn_kobo);
IF outcome<>'ok' THEN RAISE EXCEPTION 'Starter fulfillment failed: %',outcome; END IF;
IF (SELECT count(*) FROM public.nft_ownerships WHERE user_id=seller AND plan_purchase_id IS NOT NULL)<>before_count+1 THEN RAISE EXCEPTION 'Paid Starter did not mint NFT'; END IF;
IF public.fulfill_payment(payment.reference,payment.amount_ngn_kobo)<>'already' THEN RAISE EXCEPTION 'Fulfillment not idempotent'; END IF;
quote:=public.prepare_checkout_for_user(seller,'plan',pro,NULL,1600);
SELECT * INTO payment FROM public.payments WHERE reference=quote->>'reference';
IF payment.amount_usd<>5 THEN RAISE EXCEPTION 'Starter to Pro must cost full $5'; END IF;
PERFORM public.fulfill_payment(payment.reference,payment.amount_ngn_kobo);
IF (SELECT count(*) FROM public.nft_ownerships WHERE user_id=seller AND plan_purchase_id IS NOT NULL)<>2 THEN RAISE EXCEPTION 'Upgrade must retain both NFTs'; END IF;
PERFORM set_config('request.jwt.claim.sub',seller::text,true);
sess:=public.start_mining(); sess_id:=(sess->>'id')::uuid;
SELECT o.id INTO ownership FROM public.nft_ownerships o JOIN public.nfts n ON n.id=o.nft_id WHERE o.user_id=seller AND n.mining_plan_id=pro AND o.plan_purchase_id IS NOT NULL;
IF (SELECT ownership_id FROM public.mining_sessions WHERE id=sess_id)<>ownership THEN RAISE EXCEPTION 'Highest owned NFT should mine'; END IF;
IF NOT EXISTS(SELECT 1 FROM public.mining_nft_events WHERE ownership_id=ownership AND kind='upgrade' AND (details->>'amount_usd')::numeric=5) THEN RAISE EXCEPTION 'Upgrade event missing'; END IF;
listing:=public.nft_market_action('list',ownership,5);
IF (SELECT status FROM public.mining_sessions WHERE id=sess_id)<>'active' THEN RAISE EXCEPTION 'Listing alone must not stop mining'; END IF;
IF NOT EXISTS(SELECT 1 FROM public.mining_nft_events WHERE ownership_id=ownership AND kind='listed') THEN RAISE EXCEPTION 'Listing event missing'; END IF;
PERFORM set_config('request.jwt.claim.sub',buyer::text,true);
INSERT INTO public.ledger_entries(user_id,account,amount,kind,reference) VALUES(buyer,'mvt',100000000,'test','TEST-'||gen_random_uuid());
PERFORM public.nft_market_action('buy',listing,NULL);
IF (SELECT user_id FROM public.nft_ownerships WHERE id=ownership)<>buyer THEN RAISE EXCEPTION 'Ownership must transfer to buyer'; END IF;
IF (SELECT status FROM public.mining_sessions WHERE id=sess_id)<>'cancelled' THEN RAISE EXCEPTION 'Sale must cancel seller session'; END IF;
IF NOT EXISTS(SELECT 1 FROM public.mining_nft_events WHERE ownership_id=ownership AND kind='transfer' AND actor_id=seller AND other_user_id=buyer) THEN RAISE EXCEPTION 'Transfer event missing'; END IF;
IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(public.my_mining_nft_timeline()) e WHERE e->>'ownership_id'=ownership::text AND e->>'owned'='true') THEN RAISE EXCEPTION 'Buyer timeline missing'; END IF;
sess:=public.start_mining();
IF (sess->>'ownership_id')::uuid<>ownership THEN RAISE EXCEPTION 'Resale buyer must gain mining access'; END IF;
UPDATE public.mining_sessions SET ends_at=now()-interval '1 second' WHERE id=(sess->>'id')::uuid;
IF (public.claim_mining((sess->>'id')::uuid)->>'reward')::numeric<>12 THEN RAISE EXCEPTION 'Buyer must get Pro reward of 12 MVG'; END IF;
PERFORM set_config('request.jwt.claim.sub',seller::text,true);
IF NOT EXISTS(SELECT 1 FROM jsonb_array_elements(public.my_mining_nft_timeline()) e WHERE e->>'ownership_id'=ownership::text AND e->>'owned'='false') THEN RAISE EXCEPTION 'Seller lost transferred NFT history'; END IF;
BEGIN PERFORM public.claim_mining(sess_id); RAISE EXCEPTION 'Sold NFT session was claimable'; EXCEPTION WHEN raise_exception THEN IF SQLERRM='Sold NFT session was claimable' THEN RAISE; END IF; END;
sess:=public.start_mining();
IF (SELECT pp.plan_id FROM public.plan_purchases pp WHERE pp.id=(sess->>'purchase_id')::uuid)<>starter THEN RAISE EXCEPTION 'Seller must retain Starter mining access'; END IF;
quote:=public.prepare_checkout_for_user(buyer,'plan',team,NULL,1600);
IF (quote->>'usd')::numeric<>10 THEN RAISE EXCEPTION 'Pro to Team must cost full $10'; END IF;
UPDATE public.payments SET status='failed' WHERE reference=quote->>'reference';
PERFORM set_config('request.jwt.claim.sub',buyer::text,true);
quote:=public.prepare_checkout('plan',team,NULL,1600);
IF (quote->>'usd')::numeric<>10 THEN RAISE EXCEPTION 'Authenticated Team checkout must cost $10'; END IF;
PERFORM set_config('request.jwt.claim.sub','',true);
IF public.my_mining_nft_timeline()<>'[]'::jsonb THEN RAISE EXCEPTION 'Signed-out timeline leaked'; END IF;
END $$;
ROLLBACK;